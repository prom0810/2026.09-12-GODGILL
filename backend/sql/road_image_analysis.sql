CREATE TABLE IF NOT EXISTS road_image_analysis (
    image_analysis_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    image_name VARCHAR(255) NOT NULL,
    latitude DOUBLE PRECISION NOT NULL,
    longitude DOUBLE PRECISION NOT NULL,
    direction VARCHAR(10) NOT NULL,

    sidewalk_ratio DOUBLE PRECISION NOT NULL DEFAULT 0,
    roadway_ratio DOUBLE PRECISION NOT NULL DEFAULT 0,
    alley_ratio DOUBLE PRECISION NOT NULL DEFAULT 0,

    person_count INTEGER NOT NULL DEFAULT 0,
    vehicle_count INTEGER NOT NULL DEFAULT 0,
    obstacle_count INTEGER NOT NULL DEFAULT 0,

    vehicle_sidewalk_overlap DOUBLE PRECISION NOT NULL DEFAULT 0,
    obstacle_sidewalk_overlap DOUBLE PRECISION NOT NULL DEFAULT 0,

    near_vehicle_count INTEGER NOT NULL DEFAULT 0,
    near_obstacle_count INTEGER NOT NULL DEFAULT 0,
    mean_vehicle_proximity DOUBLE PRECISION NOT NULL DEFAULT 0,
    mean_obstacle_proximity DOUBLE PRECISION NOT NULL DEFAULT 0,
    scene_openness DOUBLE PRECISION NOT NULL DEFAULT 0,

    image_risk DOUBLE PRECISION NOT NULL,
    risk_level VARCHAR(20) NOT NULL,

    model_version VARCHAR(50) NOT NULL DEFAULT 'risk-v2',
    analyzed_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT uq_road_image_analysis
        UNIQUE (image_name, model_version)
);

CREATE INDEX IF NOT EXISTS idx_road_image_analysis_location
    ON road_image_analysis(latitude, longitude);
