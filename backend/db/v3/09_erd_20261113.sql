-- 1. bpm_log 추가
--    심박 이상 SOS(emergency_event.type = 'ABNORMAL_HEART_RATE')의 발생 당시·종료 시 심박. 사건당 1행.
--    낙상·직접 누른 SOS는 저장하지 않음. heart_rate_record·motion_record는 용도 미정으로 보류(그대로 둠).
-- 2. emergency_event.lat / lng 삭제 → SOS 위치는 sos_log에만 둔다
--    삭제 전에, sos_log에 위치가 하나도 없는 사건의 발생 위치(lat/lng)를 sos_log로 옮긴다
--    (session_id = 'sos-' || emergency_id, recorded_at = occurred_at — 서버가 SOS 위치에 쓰는 세션 이름과 같음).
--
-- 사전 조건: sos_log가 있어야 함 (main의 08_sos_location_log.sql). 없으면 아무것도 바꾸지 않고 중단.
-- 주의: 이 파일을 실행하면 emergency_event.lat/lng를 매핑하는 백엔드(EmergencyEvent 엔티티)는
--       ddl-auto=validate에서 시작에 실패한다. 백엔드에서 lat/lng를 뺀 버전과 함께 적용할 것.
-- 여러 번 실행해도 안전 (이미 적용된 부분은 건너뜀). 빈 DB(01로 생성)에는 실행하지 않음.
-- =====================================================================

BEGIN;

DO $$
BEGIN
    IF to_regclass('public.sos_log') IS NULL THEN
        RAISE EXCEPTION 'sos_log 테이블이 없습니다. 08_sos_location_log.sql(main)을 먼저 실행하세요.';
    END IF;
END $$;

-- ---------------------------------------------------------------------
-- 1. bpm_log
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS bpm_log (
    bpm_log_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    emergency_id  BIGINT   NOT NULL,
    bpm_start     SMALLINT NOT NULL,
    bpm_end       SMALLINT NOT NULL,
    CONSTRAINT fk_bpm_log_emergency FOREIGN KEY (emergency_id)
        REFERENCES emergency_event (emergency_id) ON DELETE RESTRICT,
    CONSTRAINT uq_bpm_log_emergency UNIQUE (emergency_id),
    CONSTRAINT ck_bpm_log_bpm CHECK (bpm_start > 0 AND bpm_end > 0)
);
COMMENT ON TABLE bpm_log IS '심박 이상 SOS(emergency_event.type = ABNORMAL_HEART_RATE)의 발생 당시·종료 시 심박. 사건당 1행, SOS 종료 때 서버가 저장';
COMMENT ON COLUMN bpm_log.bpm_start IS '심박수로 인한 SOS 발생 당시 심박 (워치 감지 값, 없으면 SOS 후 첫 측정값)';
COMMENT ON COLUMN bpm_log.bpm_end IS '심박수로 인한 SOS 종료 시 심박 (SOS 동안 마지막 측정값)';
-- 04_enable_rls.sql을 적용한 DB와 맞춘다 (Supabase REST API로 읽지 못하게)
ALTER TABLE bpm_log ENABLE ROW LEVEL SECURITY;

-- ---------------------------------------------------------------------
-- 2. emergency_event.lat / lng → sos_log
-- ---------------------------------------------------------------------
DO $$
DECLARE
    moved INTEGER;
BEGIN
    IF NOT EXISTS (SELECT 1 FROM information_schema.columns
                   WHERE table_schema = 'public' AND table_name = 'emergency_event' AND column_name = 'lat') THEN
        RAISE NOTICE 'emergency_event.lat/lng가 이미 없습니다. 건너뜀';
        RETURN;
    END IF;

    INSERT INTO sos_log (emergency_id, session_id, lat, lng, accuracy, recorded_at)
    SELECT e.emergency_id, 'sos-' || e.emergency_id, e.lat, e.lng, NULL, e.occurred_at
    FROM emergency_event e
    WHERE e.lat IS NOT NULL AND e.lng IS NOT NULL
      AND NOT EXISTS (SELECT 1 FROM sos_log s WHERE s.emergency_id = e.emergency_id);
    GET DIAGNOSTICS moved = ROW_COUNT;
    RAISE NOTICE 'emergency_event 발생 위치 % 건을 sos_log로 옮김', moved;

    ALTER TABLE emergency_event
        DROP CONSTRAINT IF EXISTS ck_emergency_lat_lng_pair,
        DROP CONSTRAINT IF EXISTS ck_emergency_lat,
        DROP CONSTRAINT IF EXISTS ck_emergency_lng,
        DROP COLUMN lat,
        DROP COLUMN lng;
END $$;

COMMENT ON TABLE emergency_event IS 'SOS 및 센서 자동 감지 긴급 사건. 위치(발생 위치·이동 기록)는 sos_log';

COMMIT;
