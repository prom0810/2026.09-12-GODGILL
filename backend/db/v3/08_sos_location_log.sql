-- Run once on an existing PostgreSQL v3 database before deploying the SOS GPS change.
BEGIN;

CREATE TABLE IF NOT EXISTS sos_log (
    sos_log_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    emergency_id BIGINT NOT NULL REFERENCES emergency_event (emergency_id) ON DELETE CASCADE,
    lat DOUBLE PRECISION NOT NULL,
    lng DOUBLE PRECISION NOT NULL
);

-- The first four columns also match the earlier SOS ERD. Extend that table if it exists.
ALTER TABLE sos_log ADD COLUMN IF NOT EXISTS session_id VARCHAR(100);
ALTER TABLE sos_log ADD COLUMN IF NOT EXISTS recorded_at TIMESTAMPTZ;
ALTER TABLE sos_log ADD COLUMN IF NOT EXISTS accuracy DOUBLE PRECISION;

DO $$ BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid = 'sos_log'::regclass AND conname = 'ck_sos_log_lat') THEN
        ALTER TABLE sos_log ADD CONSTRAINT ck_sos_log_lat CHECK (lat BETWEEN -90 AND 90);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid = 'sos_log'::regclass AND conname = 'ck_sos_log_lng') THEN
        ALTER TABLE sos_log ADD CONSTRAINT ck_sos_log_lng CHECK (lng BETWEEN -180 AND 180);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid = 'sos_log'::regclass AND conname = 'ck_sos_log_accuracy') THEN
        ALTER TABLE sos_log ADD CONSTRAINT ck_sos_log_accuracy CHECK (accuracy IS NULL OR accuracy >= 0);
    END IF;
END $$;
CREATE UNIQUE INDEX IF NOT EXISTS ux_sos_log_fix ON sos_log (emergency_id, session_id, recorded_at);
CREATE INDEX IF NOT EXISTS ix_sos_log_event_time ON sos_log (emergency_id, recorded_at);
CREATE INDEX IF NOT EXISTS ix_sos_log_session_time ON sos_log (session_id, recorded_at);
ALTER TABLE sos_log ENABLE ROW LEVEL SECURITY;

COMMIT;
